def create_ukraine_roads_graph() -> Graph:
    graph = Graph()
    for vertex_id, (name, x, y) in enumerate(CITY_COORDINATES, start=1):
        graph.add_vertex(Vertex(vertex_id, name, x, y))
    ids_by_name = {vertex.name: vertex.id for vertex in graph.vertices.values()}
    for source_name, target_name, distance in ROAD_DISTANCES:
        graph.add_edge(ids_by_name[source_name], ids_by_name[target_name], distance)
    return graph